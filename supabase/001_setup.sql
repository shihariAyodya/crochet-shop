-- ── 1. Who is the admin? ─────────────────────────────────────
create or replace function public.is_admin()
returns boolean
language sql
stable
set search_path = ''
as $$
  select coalesce((auth.jwt() ->> 'email') = 'shihariayodya@gmail.com', false);
$$;


-- ── 2. Products table ───────────────────────────────────────
create table if not exists public.products (
  id          bigint generated by default as identity primary key,
  name        text        not null,
  category    text        not null,
  description text,
  price       text,                              -- one price for all sizes, e.g. 'Rs. 2,800'
  prices      jsonb,                             -- or a price per size, e.g. {"S": "Rs. 2,500"}
  sizes       text[]      not null default '{}',
  colors      jsonb       not null default '[]', -- [{name, hex, available, imageIndex}]
  images      text[]      not null default '{}', -- photo URLs
  is_active   boolean     not null default true, -- false = hidden from the shop
  sort_order  integer     not null default 0,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index if not exists products_category_idx on public.products (category);

-- keep updated_at fresh
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists products_set_updated_at on public.products;
create trigger products_set_updated_at
  before update on public.products
  for each row execute function public.set_updated_at();


-- ── 3. Feedback table (from the contact form) ───────────────
create table if not exists public.feedback (
  id         bigint generated by default as identity primary key,
  name       text        not null check (char_length(name) between 1 and 100),
  rating     smallint    check (rating between 1 and 5),
  message    text        not null check (char_length(message) between 1 and 2000),
  created_at timestamptz not null default now()
);


-- ── 4. Security (Row Level Security) ────────────────────────
alter table public.products enable row level security;
alter table public.feedback enable row level security;

-- Products: everyone can see active products, admin sees all
drop policy if exists "Public can view active products" on public.products;
create policy "Public can view active products"
  on public.products for select
  to anon, authenticated
  using (is_active or public.is_admin());

-- Products: only admin can add / edit / delete
drop policy if exists "Admin can insert products" on public.products;
create policy "Admin can insert products"
  on public.products for insert
  to authenticated
  with check (public.is_admin());

drop policy if exists "Admin can update products" on public.products;
create policy "Admin can update products"
  on public.products for update
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists "Admin can delete products" on public.products;
create policy "Admin can delete products"
  on public.products for delete
  to authenticated
  using (public.is_admin());

-- Feedback: anyone can send, only admin can read / delete
drop policy if exists "Anyone can send feedback" on public.feedback;
create policy "Anyone can send feedback"
  on public.feedback for insert
  to anon, authenticated
  with check (true);

drop policy if exists "Admin can read feedback" on public.feedback;
create policy "Admin can read feedback"
  on public.feedback for select
  to authenticated
  using (public.is_admin());

drop policy if exists "Admin can delete feedback" on public.feedback;
create policy "Admin can delete feedback"
  on public.feedback for delete
  to authenticated
  using (public.is_admin());

-- Table permissions (RLS above still decides which rows)
grant select on public.products to anon, authenticated;
grant insert, update, delete on public.products to authenticated;
grant insert on public.feedback to anon, authenticated;
grant select, delete on public.feedback to authenticated;


-- ── 5. Photo storage ────────────────────────────────────────
insert into storage.buckets (id, name, public)
values ('product-images', 'product-images', true)
on conflict (id) do nothing;

drop policy if exists "Public can view product images" on storage.objects;
create policy "Public can view product images"
  on storage.objects for select
  to anon, authenticated
  using (bucket_id = 'product-images');

drop policy if exists "Admin can upload product images" on storage.objects;
create policy "Admin can upload product images"
  on storage.objects for insert
  to authenticated
  with check (bucket_id = 'product-images' and public.is_admin());

drop policy if exists "Admin can update product images" on storage.objects;
create policy "Admin can update product images"
  on storage.objects for update
  to authenticated
  using (bucket_id = 'product-images' and public.is_admin());

drop policy if exists "Admin can delete product images" on storage.objects;
create policy "Admin can delete product images"
  on storage.objects for delete
  to authenticated
  using (bucket_id = 'product-images' and public.is_admin());


